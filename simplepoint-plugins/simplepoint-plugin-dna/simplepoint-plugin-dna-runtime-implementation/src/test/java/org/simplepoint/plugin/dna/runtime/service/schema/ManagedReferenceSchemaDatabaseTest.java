/** All constraints are generated by DNA; raw SQL is used only to attempt business data violations. */
class ManagedReferenceSchemaDatabaseTest {
  @Test
  void postgresqlPublishesAndEvolvesTenantQualifiedReferences() throws Exception {
    verify(true);
  }

  @Test
  void mysqlPublishesAndEvolvesTenantQualifiedReferences() throws Exception {
    verify(false);
  }

  private void verify(boolean postgres) throws Exception {
    String prefix = "DNA_RUNTIME_TEST_" + (postgres ? "POSTGRES" : "MYSQL");
    String url = System.getenv(prefix + "_URL");
    Assumptions.assumeTrue(url != null && !url.isBlank(), "Disposable database is required");
    var source = new DriverManagerDataSource(url, System.getenv(prefix + "_USER"), System.getenv(prefix + "_PASSWORD"));
    var codec = new PhysicalSchemaSnapshotCodec(new ObjectMapper());
    JdbcDatabaseDialect core = postgres ? new PostgresqlJdbcDatabaseDialect() : new MysqlJdbcDatabaseDialect();
    var dialect = postgres ? new PostgresqlRuntimeSchemaDialect(codec) : new MysqlRuntimeSchemaDialect(codec);
    String suffix = UUID.randomUUID().toString().replace("-", "");
    String parentTable = "sp_ref_parent_" + suffix;
    String childTable = "sp_ref_child_" + suffix;
    try (var connection = source.getConnection(); var statement = connection.createStatement()) {
      var metadata = connection.getMetaData();
      var context = new JdbcDatabaseDialect.SupportContext(core.code(), metadata.getDriverName(), metadata.getDatabaseProductName(),
          metadata.getDatabaseProductVersion(), connection.getCatalog(), connection.getSchema(), metadata.getIdentifierQuoteString(), Map.of());
      var database = new DatabaseIdentity(metadata.getDatabaseProductName(), metadata.getDatabaseProductVersion(),
          metadata.getDatabaseMajorVersion(), metadata.getDatabaseMinorVersion());
      var parent = new PhysicalSchemaTarget("customer", new RuntimeMetadataTarget("test", connection.getCatalog(),
          postgres ? connection.getSchema() : null, parentTable));
      var child = new PhysicalSchemaTarget("trade", new RuntimeMetadataTarget("test", connection.getCatalog(),
          postgres ? connection.getSchema() : null, childTable), Map.of("customer", parent.metadataTarget()));
      var root = new PhysicalSchemaDefinition(DnaRuntimeApiVersion.CURRENT, List.of(), List.of(), null, true);
      try {
        execute(connection, core, context, dialect, parent, dialect.planInitial(connection, core, context, database, parent, "客户", root));
        insert(connection, parentTable, 1, "tenant-a", null, null);
        for (boolean unique : List.of(false, true)) {
          var legacy = schema("customer_id", List.of());
          var reference = new LogicalReferenceDefinition("trade-customer", "customer", "customer", unique);
          var related = schema("customer_id", List.of(reference));
          execute(connection, core, context, dialect, child, dialect.planInitial(connection, core, context, database, child, "交易", legacy));
          insert(connection, childTable, 10, "tenant-b", "customer_id", 1);
          assertThatThrownBy(() -> dialect.planEvolution(connection, core, context, database, child, "交易", legacy, related))
              .isInstanceOfSatisfying(DnaRuntimeException.class,
                  failure -> assertThat(failure.errorCode()).isEqualTo(DnaRuntimeErrorCode.SCHEMA_PRECHECK_FAILED));
          statement.executeUpdate("DELETE FROM " + childTable);
          insert(connection, childTable, 10, "tenant-a", "customer_id", 1);
          if (unique) {
            insert(connection, childTable, 11, "tenant-a", "customer_id", 1);
            assertThatThrownBy(() -> dialect.planEvolution(connection, core, context, database, child, "交易", legacy, related))
                .isInstanceOfSatisfying(DnaRuntimeException.class,
                    failure -> assertThat(failure.errorCode()).isEqualTo(DnaRuntimeErrorCode.SCHEMA_PRECHECK_FAILED));
            statement.executeUpdate("DELETE FROM " + childTable + " WHERE id='" + id(11) + "'");
          }
          var plan = dialect.planEvolution(connection, core, context, database, child, "交易", legacy, related);
          assertThat(plan.steps()).extracting(PlannedSchemaStep::operation)
              .contains(SchemaMigrationOperation.CREATE_INDEX, SchemaMigrationOperation.ADD_FOREIGN_KEY);
          // Simulate soft deletion after the preflight but before installing the FK.
          statement.executeUpdate("UPDATE " + parentTable + " SET deleted_at=CURRENT_TIMESTAMP WHERE id='" + id(1) + "'");
          execute(connection, core, context, dialect, child, plan);
          assertThatThrownBy(() -> dialect.verifyReferenceData(connection, core, context, child, related,
              dialect.inspect(connection, core, context, child))).isInstanceOfSatisfying(DnaRuntimeException.class,
                  failure -> assertThat(failure.errorCode()).isEqualTo(DnaRuntimeErrorCode.SCHEMA_PRECHECK_FAILED));
          statement.executeUpdate("UPDATE " + parentTable + " SET deleted_at=NULL WHERE id='" + id(1) + "'");
          dialect.verifyReferenceData(connection, core, context, child, related, dialect.inspect(connection, core, context, child));
          assertThatThrownBy(() -> insert(connection, childTable, 12, "tenant-b", "customer_id", 1)).isInstanceOf(SQLException.class);
          if (unique) assertThatThrownBy(() -> insert(connection, childTable, 12, "tenant-a", "customer_id", 1)).isInstanceOf(SQLException.class);
          else insert(connection, childTable, 12, "tenant-a", "customer_id", 1);
          insert(connection, childTable, 13, "tenant-a", "customer_id", null);
          insert(connection, childTable, 14, "tenant-a", "customer_id", null);
          assertThatThrownBy(() -> statement.executeUpdate("DELETE FROM " + parentTable + " WHERE id='" + id(1) + "'"))
              .isInstanceOf(SQLException.class);
          var renamed = schema("client_id", List.of(reference));
          var rename = dialect.planEvolution(connection, core, context, database, child, "交易", related, renamed);
          assertThat(rename.steps()).extracting(PlannedSchemaStep::operation).containsSubsequence(
              SchemaMigrationOperation.DROP_FOREIGN_KEY, SchemaMigrationOperation.RENAME_COLUMN, SchemaMigrationOperation.ADD_FOREIGN_KEY);
          execute(connection, core, context, dialect, child, rename);
          assertThatThrownBy(() -> insert(connection, childTable, 15, "tenant-b", "client_id", 1)).isInstanceOf(SQLException.class);
          assertThatThrownBy(() -> dialect.planEvolution(connection, core, context, database, child, "交易", renamed,
              schema("client_id", List.of()))).isInstanceOf(DnaRuntimeException.class);
          // Fresh publication must generate the same target constraints, not just upgrades.
          statement.execute("DROP TABLE " + childTable);
          execute(connection, core, context, dialect, child, dialect.planInitial(connection, core, context, database, child, "交易", related));
          assertThatThrownBy(() -> insert(connection, childTable, 16, "tenant-b", "customer_id", 1)).isInstanceOf(SQLException.class);
          statement.execute("DROP TABLE " + childTable);
        }
      } finally {
        statement.execute("DROP TABLE IF EXISTS " + childTable);
        statement.execute("DROP TABLE IF EXISTS " + parentTable);
      }
    }
  }

  private static PhysicalSchemaDefinition schema(String column, List<LogicalReferenceDefinition> references) {
    return new PhysicalSchemaDefinition(DnaRuntimeApiVersion.CURRENT, List.of(new LogicalFieldDefinition("customer", column, "客户", LogicalFieldType.UUID,
        true, null, null, null, null)), List.of(), null, null, references);
  }

  private static void execute(Connection connection, JdbcDatabaseDialect core, JdbcDatabaseDialect.SupportContext context,
      AbstractRuntimeSchemaDialect dialect, PhysicalSchemaTarget target, InitialSchemaPlan plan) throws Exception {
    var codec = new SchemaPlanCodec(new ObjectMapper(), new PhysicalSchemaSnapshotCodec(new ObjectMapper()));
    var binding = new SchemaPlanCodec.PlanBinding("tenant", "migration", target, null, 1, "a".repeat(64));
    var stored = codec.encode(binding, plan);
    var restored = codec.decode(binding, stored.json(), stored.checksum());
    assertThat(restored).isEqualTo(plan);
    assertThat(dialect.inspect(connection, core, context, target).checksum()).isEqualTo(restored.checkpointChecksums().getFirst());
    for (var step : restored.steps()) {
      try (var statement = connection.createStatement()) { statement.execute(step.statementSql()); }
      assertThat(dialect.inspect(connection, core, context, target).checksum())
          .as("%s step %s %s", dialect.dialectId(), step.sequence(), step.operation())
          .isEqualTo(plan.checkpointChecksums().get(step.sequence()));
    }
  }

  private static void insert(Connection connection, String table, int number, String tenant, String reference, Integer target) throws SQLException {
    String columns = "id,tenant_id,created_by,created_at,updated_by,updated_at" + (reference == null ? "" : "," + reference);
    String values = "?,?, 'actor',CURRENT_TIMESTAMP,'actor',CURRENT_TIMESTAMP" + (reference == null ? "" : ",?");
    try (var statement = connection.prepareStatement("INSERT INTO " + table + " (" + columns + ") VALUES (" + values + ")")) {
      statement.setString(1, id(number)); statement.setString(2, tenant);
      if (reference != null) statement.setString(3, target == null ? null : id(target));
      statement.executeUpdate();
    }
  }

  private static String id(int number) {
    return new UUID(0, number).toString();
  }
}
