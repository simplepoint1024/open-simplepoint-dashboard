import assert from 'node:assert/strict';
export async function smokeTenantPackages({clickMenu, clickReady, clickText, poll, evaluate, fixture, workspace}) {
  fixture.enable();
  await evaluate(`localStorage.setItem('sp.tenantId',${JSON.stringify(workspace.tenantId)});window.dispatchEvent(new CustomEvent('sp-set-tenant',{detail:${JSON.stringify(workspace.tenantId)}}));`);
  await clickMenu('我的套餐标准测试');
  const root = '.nb-tab-panel-active', pending = root + ' tr[data-row-key=package-pending]', legacy = root + ' tr[data-row-key=package-legacy]';
  await poll(() => evaluate(`document.querySelector('${pending}')?.textContent.includes('团队办公')`), 'actual package schema and list');
  assert.equal(await evaluate(`!!document.querySelector('${root} .tenant-home-hero')`), false, 'directory retains height for standard list');
  assert.equal(await evaluate(`!![...document.querySelectorAll('${legacy} button')].find(button=>button.textContent.includes('激活')&&!button.disabled)`), false);
  await clickReady(root + ' button[aria-label="切换为卡片"]');
  await poll(() => evaluate(`document.querySelectorAll('${root} .sp-record-card').length===2`), 'package card presentation');
  assert.equal(await evaluate(`[...document.querySelectorAll('${root} .sp-record-card .sp-table-row-action')].filter(button=>button.textContent.includes('资源明细')).length`), 2, 'one action group per card');
  assert.equal(await evaluate(`[...document.querySelectorAll('${root} .sp-record-card .sp-table-row-action')].filter(button=>button.textContent.includes('激活')).length`), 1, 'row capability hides activation from historical instances');
  await clickReady(root + ' button[aria-label="切换为列表"]');
  await poll(() => evaluate(`!!document.querySelector('${pending}')`), 'list presentation restored');
  await clickText(pending + ' .sp-table-button', '激活');
  const modal = '.tenant-package-activation .ant-modal';
  await poll(() => evaluate(`document.querySelector('${modal}')?.textContent.includes('开始计时')`), 'activation requires explicit confirmation');
  await clickReady(modal + ' .ant-modal-close');
  assert.equal(fixture.writes.length, 0);
  await clickText(pending + ' .sp-table-button', '激活'); fixture.failNext();
  await evaluate(`(()=>{const b=document.querySelector('${modal} .ant-btn-primary');b.click();b.click()})()`);
  await poll(() => fixture.writes.length === 1, 'one activation dispatch per confirmed attempt');
  assert.equal(await evaluate(`!!document.querySelector('${modal} .ant-modal-close')`), false);
  await poll(() => evaluate(`document.querySelector('${modal} .ant-alert-error')?.textContent.includes('激活失败')`), 'failed request preserves same instance for retry');
  await clickReady(modal + ' .ant-btn-primary');
  await poll(() => evaluate(`!document.querySelector('${modal}')&&document.querySelector('${pending}')?.textContent.includes('已激活')`), 'committed state reloaded');
  assert.deepEqual(fixture.writes.map(write=>write.id), ['package-pending', 'package-pending']);
  await clickText(pending + ' .sp-table-button', '资源明细');
  const drawer = '.ant-drawer-open';
  await poll(() => evaluate(`document.querySelector('${drawer}')?.textContent.includes('办公资源0')`), 'resource entitlement detail');
  assert.equal(await evaluate(`document.querySelector('${drawer} tr[data-row-key=package-pending-0]')?.textContent.includes('2026/12/22')`), true);
  await clickReady(drawer + ' .ant-pagination-next');
  await poll(() => evaluate(`!!document.querySelector('${drawer} tr[data-row-key=package-pending-20]')`), 'server resource pagination');
  fixture.delayReads(600);
  await clickReady(drawer + ' .ant-pagination-next'); await clickReady(drawer + ' .ant-drawer-close');
  await clickText(legacy + ' .sp-table-button', '资源明细');
  await poll(() => evaluate(`document.querySelector('${drawer} tr[data-row-key=package-legacy-0]')?.textContent.includes('无限期')`), 'new instance fences delayed previous read');
  assert.equal(await evaluate(`!!document.querySelector('${drawer} tr[data-row-key^=package-pending]')`), false);
  await clickMenu('首页');
  await poll(() => evaluate(`!document.querySelector('${drawer}')`), 'retained package drawer follows owning page');
  await clickMenu('我的套餐标准测试');
  await poll(() => evaluate(`!!document.querySelector('${drawer} tr[data-row-key=package-legacy-0]')`), 'restored package drawer reloads selected instance');
  await clickReady(drawer + ' .ant-drawer-close');
  workspace.profile.packageManageable = false;
  await clickMenu('租户设置标准测试');
  await clickText(root + ' .tenant-home-actions .sp-table-button', '刷新');
  await poll(() => evaluate(`![...document.querySelectorAll('${root} .ant-tabs-tab')].some(tab=>tab.textContent.includes('我的套餐'))`), 'owner capability revoked');
  await clickMenu('我的套餐标准测试');
  await poll(() => evaluate(`document.querySelector('${root}')?.textContent.includes('仅当前工作空间负责人')`), 'owner permission rechecked for retained page');
  assert.ok(fixture.requests.filter(request=>request.path.endsWith('/resources')).every(request=>Number(request.query.get('size')) <= 100));
  fixture.disable();
}
