import assert from 'node:assert/strict';

export async function smokeFormExtensions({action, clickReady, clickText, fill, poll, evaluate}) {
  const root = '.nb-tab-panel-active';
  const initial = await evaluate(`document.querySelectorAll('${root} [data-design-node]').length`);
  await clickReady(root + ' .sp-form-canvas-node.is-root > .sp-form-canvas-title');
  await clickText(root + ' [data-palette-type="layout.matrix"] button', '网格布局');
  await clickText(root + ' .sp-form-property-tabs .ant-tabs-tab', '布局与展示');
  await fill(root + ' #matrix_property_columns', '3');
  assert.equal(await evaluate(`document.querySelectorAll('${root} [data-component-type="layout.cell"]').length`), 6);
  assert.equal(await evaluate(`!!document.querySelector('${root} [data-palette-type="layout.cell"]')`), false);
  await clickReady(root + ' .sp-form-canvas-node.is-root > .sp-form-canvas-title');
  await clickText(root + ' [data-palette-type="data.detail"] button', '明细行');
  await clickText(root + ' .sp-form-property-tabs .ant-tabs-tab', '字段');
  await poll(() => evaluate(`!!document.querySelector('${root} .sp-form-designer-properties .sp-data-table')`), 'inline detail field tab');
  await clickText(root + ' .sp-form-designer-properties button', '编辑');
  const fieldEditor = '.sp-form-data-modal .ant-modal';
  await fill(fieldEditor + ' #data_field_validation_minLength', '2');
  await fill(fieldEditor + ' #data_field_validation_maxLength', '12');
  await fill(fieldEditor + ' #data_field_validation_pattern', '^[^0-9]+$');
  await fill(fieldEditor + ' #data_field_validation_patternMessage', '明细不能包含数字');
  await clickText(fieldEditor + ' button', '应用修改');
  await poll(() => evaluate(`!document.querySelector('${fieldEditor}')?.getClientRects().length`), 'detail field rules applied').catch(async error => {console.log('FIELD VALIDATION DIAGNOSTIC', await evaluate(`document.querySelector('${fieldEditor}')?.innerText`)); throw error;});
  await clickText(root + ' .sp-form-property-tabs .ant-tabs-tab', '索引');
  await poll(() => evaluate(`document.querySelector('${root} .sp-form-designer-properties').textContent.includes('新增索引')`), 'separate index tab');
  assert.equal(await evaluate(`[...document.querySelectorAll('${root} .sp-form-property-tabs > .ant-tabs-nav .ant-tabs-tab')].every(e=>!!e.querySelector('.anticon'))`), true);
  await clickReady(root + ' .sp-form-designer-toolbar button[aria-label="预览"]');
  const preview = '.sp-form-designer-preview .ant-modal';
  await poll(() => evaluate(`!!document.querySelector('${preview} [data-detail-id]')`), 'detail runtime preview');
  const rows = preview + ' [data-detail-id]';
  await clickReady(rows + ' button[aria-label="添加明细"]');
  await poll(() => evaluate(`!!document.querySelector('${rows} .sp-form-detail-cell input')`), 'new row edits directly in its cell');
  assert.equal(await evaluate(`!!document.querySelector('.sp-form-detail-editor')`), false, 'detail input opens no second form');
  await fill(rows + ' .sp-form-detail-cell input', '12');
  await clickText(preview + ' button', '提交');
  await poll(() => evaluate(`document.querySelector('${rows}').textContent.includes('明细不能包含数字')`), 'custom pattern error stays in its detail cell');
  await fill(rows + ' .sp-form-detail-cell input', '中文・日本語');
  await clickText(rows + ' button', '完成');
  await poll(() => evaluate(`document.querySelector('${rows}').textContent.includes('中文・日本語')`), 'detail row draft retained');
  await clickReady(rows + ' button[aria-label="添加明细"]');
  await fill(rows + ' .sp-form-detail-cell input', '最新明细');
  await clickText(rows + ' button', '完成');
  assert.equal(await evaluate(`document.querySelector('${rows} .ant-table-tbody tr[data-row-key] td:not(.ant-table-selection-column)').textContent`), '最新明细', 'new detail is the first row');
  await clickText(rows + ' button', '编辑');
  await fill(rows + ' .sp-form-detail-cell input', '编辑后的明细');
  await clickText(rows + ' button', '完成');
  await clickText(rows + ' button', '删除');
  await poll(() => evaluate(`!document.querySelector('${rows}').textContent.includes('编辑后的明细') && document.querySelector('${rows}').textContent.includes('中文・日本語')`), 'inline delete preserves the other row');
  await clickReady(preview + ' .ant-modal-close');
  for (let i = 0; i < 4; i++) await action('撤销');
  assert.equal(await evaluate(`document.querySelectorAll('${root} [data-design-node]').length`), initial);
  console.log('PASS: matrix 2x3 cells, icon property tabs and detail validation and platform detail-row add/edit/remove with Unicode values');
}
