import assert from 'node:assert/strict';
import {setTimeout as delay} from 'node:timers/promises';

export async function smokeRedis({clickMenu, clickReady, clickText, fill, poll, evaluate, fixture}) {
  const panel = '.nb-tab-panel-active .monitoring-redis-page';
  const row = index => `${panel} tr[data-row-key="Item${String(index).padStart(3, '0')}"]`;
  const dropdown = '.ant-dropdown:not(.ant-dropdown-hidden) .ant-table-filter-dropdown';
  const drawer = '.sp-query-drawer';
  const modal = '.ant-modal:not([style*="display: none"])';
  fixture.snapshots.status('BUILDING');
  await clickMenu('Redis 查询测试');
  await poll(() => evaluate(`!!document.querySelector('${panel} [data-scan-status="BUILDING"]')`), 'Redis scan in progress');
  assert.equal(await evaluate(`!!document.querySelector('${panel} .ant-pagination')`), false, 'no partial/fake page totals');
  assert.equal(fixture.details.length, 0, 'list never reads values');
  await clickMenu('Runtime 查询测试');
  await delay(1200);
  const inactive = fixture.requests.length;
  await delay(1200);
  assert.equal(fixture.requests.length, inactive, 'inactive Redis tab pauses scan polling');
  fixture.snapshots.status();
  await clickMenu('Redis 查询测试');
  await poll(() => evaluate(`!!document.querySelector('${row(0)}')`), 'Redis completed page');
  assert.equal(await evaluate(`(() => {
    const root=document.querySelector('${panel}'), body=root.querySelector('.ant-table-body');
    const pagination=root.querySelector('.ant-pagination');
    return !!body && body.scrollHeight>body.clientHeight && pagination.getBoundingClientRect().bottom<=root.getBoundingClientRect().bottom+2;
  })()`), true, 'Redis scrolls inside the page and keeps pagination reachable');
  const builds = fixture.snapshots.builds;
  await clickReady(`${panel} .ant-pagination-item-26`);
  await poll(() => evaluate(`!!document.querySelector('${row(519)}')`), 'Redis page beyond 500');
  const headerAction = selector => evaluate(`(() => {
    const th=[...document.querySelectorAll('${panel} th')].find(e=>e.textContent.includes('Key'));
    if(!th?.querySelector('${selector}')) throw Error('Missing Redis header control');
    th.querySelector('${selector}').click();
  })()`);
  await headerAction('.ant-table-column-sorters');
  await poll(() => fixture.requests.some(params => params.getAll('sort').includes('key,asc') && params.get('page') === '0'), 'Redis sorting resets page');
  await headerAction('.ant-table-filter-trigger');
  await poll(() => evaluate(`!!document.querySelector('${dropdown} input.ant-input')`), 'Redis header filter');
  await fill(`${dropdown} input.ant-input`, 'Item519');
  await clickText(`${dropdown} button`, '应用');
  await poll(() => evaluate(`!!document.querySelector('${row(519)}') && document.querySelectorAll('${panel} tr[data-row-key]').length===1`), 'Redis whole snapshot filter');
  await clickReady(`${panel} button[aria-label="筛选与视图"]`);
  await clickText(`${drawer} button`, '添加条件');
  await fill(`${drawer} input.ant-input:not([placeholder*="视图名称"])`, 'no-match');
  await clickText(`${drawer} .ant-drawer-footer button`, '应用');
  await poll(() => evaluate(`document.querySelectorAll('${panel} tr[data-row-key]').length===0 && !document.querySelector('${panel} .ant-spin-spinning')`), 'Redis advanced/header intersection');
  assert.ok(fixture.requests.some(params => params.has('key') && params.has('$query')));
  await clickReady(`${panel} button[aria-label="筛选与视图"]`);
  await clickText(`${drawer} .ant-drawer-footer button`, '清空高级条件');
  await clickText(`${drawer} .ant-drawer-footer button`, '应用');
  await poll(() => evaluate(`!!document.querySelector('${row(519)}')`), 'Redis header survives advanced reset');
  await clickReady(`${panel} button[aria-label="筛选与视图"]`);
  await fill(`${drawer} input[placeholder*="视图名称"]`, 'Redis 常用视图');
  await clickText(`${drawer} button`, '保存当前视图');
  await poll(() => evaluate(`[...document.querySelectorAll('${drawer} button')].some(e=>e.textContent==='Redis 常用视图')`), 'Redis view saved');
  await clickReady(`${drawer} .ant-drawer-close`);
  await clickReady(`${panel} button[aria-label="清除全部筛选"]`);
  await poll(() => evaluate(`document.querySelectorAll('${panel} tr[data-row-key]').length===20`), 'Redis clear filters');
  await clickReady(`${panel} button[aria-label="筛选与视图"]`);
  await clickText(`${drawer} button`, 'Redis 常用视图');
  await poll(() => evaluate(`!!document.querySelector('${row(519)}') && document.querySelectorAll('${panel} tr[data-row-key]').length===1`), 'Redis restored view executes');
  assert.equal(fixture.snapshots.builds, builds, 'filter/page/sort/views reuse the same scan');
  fixture.snapshots.status('EXPIRED');
  await headerAction('.ant-table-column-sorters');
  await poll(() => evaluate(`!!document.querySelector('${panel} [data-scan-status="EXPIRED"]')`), 'Redis pinned result expired');
  assert.equal(await evaluate(`document.querySelectorAll('${panel} tr[data-row-key]').length`), 0, 'expired snapshot cannot masquerade as current data');
  fixture.snapshots.status();
  await clickText(`${panel} .redis-scan-status button`, '重试');
  await poll(() => evaluate(`!!document.querySelector('${row(519)}')`), 'Redis refresh retains filters');
  assert.equal(fixture.snapshots.builds, builds + 1);
  fixture.failQuery();
  await clickReady(`${panel} button[aria-label="刷新"]`);
  await poll(() => evaluate(`!!document.querySelector('${panel} .ant-alert-error')`), 'Redis query error is visible');
  await clickText(`${panel} .redis-scan-status button`, '重置筛选与排序');
  await poll(() => evaluate(`document.querySelectorAll('${panel} tr[data-row-key]').length===20`), 'Redis query error recovery');
  fixture.failDetail();
  await clickText(`${row(0)} button`, '查看');
  await poll(() => evaluate(`!!document.querySelector('${modal} .ant-alert-error')`), 'Redis expired key detail failure is visible');
  await clickText(`${modal} .ant-alert-error button`, '重试');
  await poll(() => evaluate(`document.querySelector('${modal} textarea')?.value==='full value'`), 'Redis detail retry');
  await clickReady(`${modal} .ant-modal-close`);
  fixture.detail({valueEncoding: 'base64', editable: false, value: 'AP8B'});
  await clickText(`${row(0)} button`, '查看');
  await poll(() => evaluate(`document.querySelector('${modal} textarea')?.value==='AP8B'`), 'Redis binary preview');
  assert.equal(await evaluate(`document.querySelector('${modal}')?.textContent.includes('Base64')`), true, 'binary preview is explicitly identified, never silently decoded');
  await clickReady(`${modal} .ant-modal-close`);
  for (const override of [{value: '***'}, {value: 'preview only', truncated: true}, {key: 'wrong-neighbour'}]) {
    fixture.detail(override);
    await clickText(`${row(0)} button`, '编辑');
    await poll(() => evaluate(`!!document.querySelector('${modal} .ant-alert-error')`), 'Redis unsafe edit blocked');
    assert.equal(await evaluate(`document.querySelector('${modal} .ant-modal-footer .ant-btn-primary')?.disabled`), true);
    await clickText(`${modal} .ant-modal-footer button`, '取消');
  }
  fixture.detail();
  await clickText(`${row(0)} button`, '编辑');
  await poll(() => evaluate(`document.querySelector('${modal} textarea')?.value==='full value'`), 'Redis full-value editor');
  await fill(`${modal} textarea`, 'unsaved draft');
  await clickText(`${modal} .ant-modal-footer button`, '取消');
  await poll(() => evaluate(`!!document.querySelector('.ant-modal-confirm')`), 'Redis discard confirmation');
  await clickText('.ant-modal-confirm button', '放弃');
  await poll(() => evaluate(`!document.querySelector('${modal} textarea')`), 'Redis draft discarded without writes');
  const beforeScope = fixture.requests.length;
  await fill(`${panel} #redis-scan-pattern`, 'Item51*');
  await clickText(`${panel} .monitoring-redis-scope button`, '应用范围');
  await poll(() => evaluate(`document.querySelectorAll('${panel} tr[data-row-key]').length===10`), 'Redis new scan scope resets query and page');
  assert.ok(fixture.requests.slice(beforeScope).some(params => params.get('scanPattern') === 'Item51*' && !params.has('snapshotId')));
  await evaluate(`(() => {
    const title=window.spI18n.t('monitoring.redis.sizeObserved');
    const th=[...document.querySelectorAll('${panel} th')].find(e=>e.textContent.includes(title));
    th.querySelector('.ant-table-filter-trigger').click();
  })()`);
  await poll(() => evaluate(`!!document.querySelector('${dropdown} input.ant-input-number-input')`), 'Redis numeric size header');
  await fill(`${dropdown} input.ant-input-number-input`, '519');
  await clickText(`${dropdown} button`, '应用');
  await poll(() => evaluate(`!!document.querySelector('${row(519)}') && document.querySelectorAll('${panel} tr[data-row-key]').length===1`), 'Redis size filter does not overwrite page size');
  assert.ok(fixture.requests.slice(beforeScope).some(params => params.get('size') === '20'
    && JSON.parse(params.get('$query') ?? '{}').where?.field === 'size'));
  for (const status of ['LIMIT_EXCEEDED', 'TIMED_OUT', 'FAILED']) {
    fixture.snapshots.status(status);
    await clickReady(`${panel} button[aria-label="刷新"]`);
    await poll(() => evaluate(`!!document.querySelector('${panel} [data-scan-status="${status}"]')`), `Redis ${status} visible`);
    assert.equal(await evaluate(`!!document.querySelector('${panel} .ant-pagination')`), false);
    fixture.snapshots.status();
    await clickText(`${panel} .redis-scan-status button`, '重试');
    await poll(() => evaluate(`!!document.querySelector('${row(519)}')`), `Redis ${status} recovery retains filters`);
  }
  assert.ok(fixture.requests.every(params => Number(params.get('size')) <= 100));
  assert.equal(await evaluate(`document.querySelector('${panel} button[aria-label="筛选与视图"]')?.textContent`), '', 'query control is icon-only');
  await clickReady('.nb-tabs-bar .ant-tabs-tab-active .ant-tabs-tab-remove');
  console.log('PASS: Redis real schema, scan pinning/poll lifecycle, >500 paging, headers, advanced intersection, views, expiry/error recovery, on-demand details and guarded editing');
}
