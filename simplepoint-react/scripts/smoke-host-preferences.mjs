import assert from 'node:assert/strict';

export async function smokeHostPreferences({clickMenu, clickReady, clickText, fill, poll, evaluate, send, chooseFile, fixture}) {
  const root = '.nb-tab-panel-active';
  await clickMenu('首页');
  await evaluate("location.hash='#/profile'");
  await poll(() => evaluate("!!document.querySelector('" + root + " .profile-nav-links')"), 'profile navigation');
  await clickReady(root + ' .profile-nav-links button:first-child');
  const form = root + ' .profile-detail-form', save = root + ' .profile-detail-actions button';
  await poll(() => evaluate("!!document.querySelector('" + form + " input#root_nickname')"), 'platform personal-profile form');
  assert.equal(await evaluate("!!document.querySelector('" + form + "').classList.contains('rjsf')"), true);
  assert.equal(await evaluate("document.querySelectorAll('" + root + " .profile-main .ant-card').length"), 0);
  assert.equal(await evaluate("document.querySelector('" + save + "').disabled"), true);
  const initialBirthday = fixture.profile().birthdate;
  await fill(form + ' input#root_nickname', 'Unsaved profile draft');
  await fill(form + ' input#root_name', '真实姓名测试');
  const file = root + ' .oss-image-upload input[type=file]';
  fixture.failUpload(413);
  const beforeFail = fixture.pictureSaves.length;
  await chooseFile(file, 1024, 'image/png', 'avatar.png');
  await poll(() => evaluate("document.querySelector('" + root + " .oss-image-upload [role=alert]')?.textContent.includes('服务端上传大小限制')"), 'avatar upload failure remains visible');
  assert.equal(fixture.pictureSaves.length, beforeFail);
  fixture.failUpload(200); fixture.failSave(500);
  await chooseFile(file, 1024, 'image/png', 'avatar.png');
  await poll(() => evaluate("document.querySelector('" + root + " .oss-image-upload [role=alert]')?.textContent.includes('头像资料保存失败')"), 'field-only avatar persistence failure');
  assert.deepEqual(fixture.pictureSaves.at(-1), {picture: '/common/object-storage/images/smoke-upload'});
  fixture.failSave(200);
  const beforeRetry = fixture.pictureSaves.length;
  await chooseFile(file, 1024, 'image/png', 'avatar.png');
  await poll(() => fixture.pictureSaves.length === beforeRetry + 1 && evaluate("!!document.querySelector('" + root + " .oss-image-upload img[src=\"/common/object-storage/images/smoke-upload\"]') && !document.querySelector('" + root + " .oss-image-upload .ant-btn-loading') && !document.querySelector('" + form + " input#root_nickname').disabled"), 'avatar succeeds without losing a dirty draft');
  assert.equal(await evaluate("document.querySelector('" + form + " input#root_nickname').value"), 'Unsaved profile draft');
  assert.notEqual(fixture.profile().nickname, 'Unsaved profile draft');
  assert.equal(await evaluate("document.querySelector('" + form + " input#root_name').value"), '真实姓名测试');
  assert.notEqual(fixture.profile().name, '真实姓名测试', 'avatar-only persistence must not save a name draft');
  fixture.delay = 250;
  let before = fixture.profileSaves.length;
  await evaluate("(() => {const button=document.querySelector('" + save + "');button.click();button.click();})()");
  await poll(() => fixture.profileSaves.length === before + 1, 'profile same-frame single flight');
  assert.equal(await evaluate("document.querySelector('" + form + " input#root_nickname').disabled"), true);
  await poll(() => evaluate("document.querySelector('" + save + "').disabled && !document.querySelector('" + form + " input#root_nickname').disabled"), 'saved form is clean');
  assert.equal(fixture.profileSaves.length, before + 1);
  assert.equal(fixture.profileSaves.at(-1).name, '真实姓名测试', 'explicit full name is persisted with the profile');
  assert.equal(fixture.profileSaves.at(-1).birthdate, initialBirthday, 'unchanged picker retains the original instant');
  for (const field of ['gender', 'locale', 'zoneinfo']) assert.equal(fixture.profileSaves.at(-1)[field], fixture.profile()[field]);
  await fill(form + ' input#root_nickname', ''); before = fixture.profileSaves.length;
  await clickReady(save);
  await poll(() => evaluate("!!document.querySelector('" + form + " .ant-form-item-has-error')"), 'required nickname is validated inline');
  assert.equal(fixture.profileSaves.length, before);
  await fill(form + ' input#root_nickname', fixture.profile().nickname);
  await poll(() => evaluate("document.querySelector('" + save + "').disabled"), 'reverting the draft clears dirty state');
  if (fixture.profile().birthdate) {
    await evaluate("document.querySelector('" + form + " input#root_birthdate').closest('.ant-picker').querySelector('.ant-picker-clear').click()");
    await poll(() => evaluate("!document.querySelector('" + save + "').disabled"), 'clearing an optional date is an explicit dirty edit');
    await clickReady(save);
    await poll(() => fixture.profile().birthdate === null && evaluate("document.querySelector('" + save + "').disabled"), 'empty date passes validation and persists null');
  }
  await clickReady(root + ' .profile-nav-links button:nth-child(4)');
  const passwordForm = root + ' .profile-password-form';
  await poll(() => evaluate("!!document.querySelector('" + passwordForm + " input#root_currentPassword')"), 'platform password form');
  assert.equal(await evaluate("document.querySelector('" + passwordForm + " input#root_currentPassword').autocomplete"), 'current-password');
  assert.equal(await evaluate("document.querySelector('" + passwordForm + " input#root_newPassword').autocomplete"), 'new-password');
  await fill(passwordForm + ' input#root_currentPassword', 'old-test-password');
  await fill(passwordForm + ' input#root_newPassword', 'new-test-password');
  await fill(passwordForm + ' input#root_confirmPassword', 'mismatched-password');
  const passwordAction = root + ' .profile-content-group:last-child .sp-table-button';
  before = fixture.passwordSaves.length;
  await clickReady(passwordAction);
  await poll(() => evaluate("document.querySelector('" + passwordForm + "').textContent.includes('两次输入的密码不一致')"), 'password mismatch is inline');
  assert.equal(fixture.passwordSaves.length, before);
  await fill(passwordForm + ' input#root_confirmPassword', 'new-test-password');
  await evaluate("(() => {const button=document.querySelector('" + passwordAction + "');button.click();button.click();})()");
  await poll(() => fixture.passwordSaves.length === before + 1, 'password mutation single flight');
  await poll(() => evaluate("document.querySelector('" + passwordForm + " input#root_currentPassword').value==='' && !document.querySelector('" + passwordAction + "').disabled"), 'passwords are cleared only after success');
  assert.equal(fixture.passwordSaves.length, before + 1); fixture.delay = 0;
  await evaluate("location.hash='#/settings'");
  await poll(() => evaluate("!!document.querySelector('" + root + " .settings-page input#root_theme')"), 'platform settings form');
  assert.equal(await evaluate("document.querySelectorAll('" + root + " .settings-page .ant-card').length"), 0);
  assert.equal(await evaluate("document.querySelector('" + root + " .settings-page').textContent.includes('示例数据')"), false);
  assert.match(await evaluate("document.querySelector('" + root + " .settings-page .ant-descriptions').textContent"), /Ant Design 6\./);
  const choose = async (id, label) => {
    await evaluate("document.querySelector('" + root + " .settings-page #" + id + "').closest('.ant-select').dispatchEvent(new MouseEvent('mousedown',{bubbles:true}))");
    await poll(() => evaluate("!![...document.querySelectorAll('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option')].find(option=>option.textContent===" + JSON.stringify(label) + ")"), 'setting choice ' + label);
    await evaluate("[...document.querySelectorAll('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option')].find(option=>option.textContent===" + JSON.stringify(label) + ").click()");
  };
  await choose('root_theme', '深色');
  await poll(() => evaluate("localStorage.getItem('sp.theme')==='dark'"), 'actual theme is persisted');
  await choose('root_size', '大');
  await poll(() => evaluate("localStorage.getItem('sp.globalSize')==='large'"), 'actual global size is persisted');
  await choose('root_theme', '跟随系统');
  await send('Emulation.setEmulatedMedia', {features: [{name: 'prefers-color-scheme', value: 'dark'}]});
  await poll(() => evaluate("document.querySelectorAll('" + root + " .settings-page .ant-tag')[1].textContent.includes('深色')"), 'live operating-system theme preview');
  await send('Emulation.setEmulatedMedia', {features: [{name: 'prefers-color-scheme', value: 'light'}]});
  await poll(() => evaluate("document.querySelectorAll('" + root + " .settings-page .ant-tag')[1].textContent.includes('浅色')"), 'preview follows system changes');
  await clickReady(root + ' .settings-form:first-child .sp-table-button');
  assert.deepEqual(await evaluate("[localStorage.getItem('sp.theme'),localStorage.getItem('sp.globalSize')]"), ['light', 'middle']);
  await choose('root_language', 'English');
  await poll(() => evaluate("document.querySelector('" + root + " .settings-page').textContent.includes('Appearance')"), 'real language changes immediately');
  await clickReady(root + ' .settings-form:nth-of-type(2) .sp-table-button');
  await poll(() => evaluate("document.querySelector('" + root + " .settings-page').textContent.includes('外观')"), 'language reset uses the actual provider');
  console.log('PASS: profile SForm validation/dates/preferences; field-only avatar with dirty draft; profile/password single flight; real settings and live theme preview');
}
