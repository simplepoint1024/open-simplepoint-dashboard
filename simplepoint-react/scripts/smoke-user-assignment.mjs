import assert from 'node:assert/strict';

export async function smokeUserAssignment({clickMenu, clickReady, clickText, fill, poll, evaluate, requests, fixture}) {
  const root = '.nb-tab-panel-active';
  const left = '.sp-assignment-panel[data-selected="false"]';
  const right = '.sp-assignment-panel[data-selected="true"]';
  const dropdown = '.ant-dropdown:not(.ant-dropdown-hidden) .ant-table-filter-dropdown';
  const hasRow = (panel, id) => evaluate(`!!document.querySelector('${panel} tr[data-row-key="${id}"]')`);
  const filter = async (panel, value) => {
    await poll(() => evaluate(`!document.querySelector('${dropdown}')`), 'old assignment filter closed');
    await evaluate(`[...document.querySelectorAll('${panel} th')].find(e=>e.textContent.includes('姓名')).querySelector('.ant-table-filter-trigger').click()`);
    await poll(() => evaluate(`!!document.querySelector('${dropdown} input.ant-input')`), 'member candidate name filter');
    await fill(`${dropdown} input.ant-input`, value);
    await clickText(`${dropdown} button`, '应用');
  };
  await clickMenu('租户成员分配测试');
  await clickReady(`${root} tr[data-row-key="tenant-a"] input[type="checkbox"]`);
  await clickText(`${root} button`, '配置成员');
  await poll(() => hasRow(right, 'user-000'), 'tenant assignment owner');
  assert.equal(await evaluate(`document.querySelector('${right} tr[data-row-key="user-000"] input[type="checkbox"]').disabled`), true, 'tenant owner cannot be selected');
  await clickReady(`${right} thead input[type="checkbox"]`);
  assert.equal(await evaluate(`document.querySelector('${right} tr[data-row-key="user-000"] input[type="checkbox"]').checked`), false, 'select-all skips the protected owner');
  await clickReady(`${right} thead input[type="checkbox"]`);
  await clickReady(`${right} .ant-pagination-item-6`);
  await poll(() => hasRow(right, 'user-119'), 'assigned users beyond 100');
  for (let i=0; i<2; i++) await evaluate(`[...document.querySelectorAll('${right} th')].find(e=>e.textContent.includes('姓名')).querySelector('.ant-table-column-sorters').click()`);
  await poll(() => evaluate(`document.querySelector('${right} tr[data-row-key]')?.dataset.rowKey==='user-119' && document.querySelector('${right} .ant-pagination-item-active')?.textContent==='1'`), 'assignment sorting runs server-side and resets pagination');
  await filter(left, 'Candidate239');
  await poll(() => hasRow(left, 'user-239'), 'off-page available candidate search');
  await clickReady(`${left} button[aria-label="筛选与视图"]`);
  await clickText('.sp-query-drawer button', '添加条件');
  await fill('.sp-query-drawer input.ant-input:not([placeholder*="视图名称"])', 'user-238');
  await clickText('.sp-query-drawer .ant-drawer-footer button', '应用');
  await poll(() => evaluate(`document.querySelectorAll('${left} tr[data-row-key]').length===0 && !document.querySelector('${left} .ant-spin-spinning')`), 'advanced assignment ID filter intersects header search');
  await clickReady(`${left} button[aria-label="筛选与视图"]`);
  await clickText('.sp-query-drawer .ant-drawer-footer button', '清空高级条件');
  await clickText('.sp-query-drawer .ant-drawer-footer button', '应用');
  await poll(() => hasRow(left, 'user-239'), 'clearing only advanced conditions preserves the header');
  await clickReady(`${left} button[aria-label="筛选与视图"]`);
  await fill('.sp-query-drawer input[placeholder*="视图名称"]', '成员分配视图');
  await clickText('.sp-query-drawer button', '保存当前视图');
  await poll(() => evaluate(`[...document.querySelectorAll('.sp-query-drawer button')].some(e=>e.textContent==='成员分配视图')`), 'assignment view saved');
  await clickReady('.sp-query-drawer .ant-drawer-close');
  await clickReady(`${left} button[aria-label="清除全部筛选"]`);
  await poll(() => hasRow(left, 'user-120'), 'clear available query');
  await clickReady(`${left} button[aria-label="筛选与视图"]`);
  await clickText('.sp-query-drawer button', '成员分配视图');
  await poll(() => hasRow(left, 'user-239'), 'restore assignment view executes query');
  await clickReady(`${left} tr[data-row-key="user-239"] input[type="checkbox"]`);
  const before = fixture.moves.length; fixture.failMove();
  await evaluate(`(() => {const b=[...document.querySelectorAll('${left} button')].find(e=>e.textContent.replaceAll(' ','')==='分配');b.click();b.click();})()`);
  await poll(() => evaluate(`document.body.textContent.includes('成员分配失败（测试）')`), 'assignment failure is visible');
  assert.equal(fixture.moves.length, before+1, 'double click produces one mutation');
  assert.equal(await evaluate(`document.querySelector('${left} tr[data-row-key="user-239"] input[type="checkbox"]').checked`), true, 'failed assignment preserves selection');
  await clickText(`${left} button`, '分配');
  await poll(() => fixture.grants.get('tenant-a').has('user-239'), 'assign succeeds');
  await poll(() => evaluate(`document.querySelectorAll('${left} tr[data-row-key]').length===0`), 'available pane refreshes');
  await filter(right, 'Candidate239');
  await poll(() => hasRow(right, 'user-239'), 'assigned pane discovers newly assigned user');
  await clickReady(`${right} tr[data-row-key="user-239"] input[type="checkbox"]`);
  await clickText(`${right} button`, '移除分配');
  await poll(() => hasRow(left, 'user-239'), 'removal refreshes available pane');
  await clickReady('.ant-drawer-open .ant-drawer-close');
  await poll(() => evaluate(`!document.querySelector('.sp-assignment-panel')`), 'first tenant session disposed');
  await clickReady(`${root} tr[data-row-key="tenant-a"] input[type="checkbox"]`);
  await clickReady(`${root} tr[data-row-key="tenant-b"] input[type="checkbox"]`);
  await clickText(`${root} button`, '配置成员');
  await poll(() => hasRow(right, 'user-001'), 'new tenant gets its own assignment side');
  assert.equal(await evaluate(`document.querySelectorAll('${right} tr[data-row-key]').length`), 1, 'previous tenant rows never reused');
  assert.equal(await evaluate(`document.querySelector('${right} tr[data-row-key="user-001"] input').disabled`), true, 'new tenant owner protected');
  assert.ok(requests.some(r=>r.url.includes('/tenants/users/items/schema?tenantId=tenant-b')), 'schema cache includes the target tenant');
  assert.equal(requests.some(r=>r.url.includes('/tenants/users/authorized')), false, 'never hydrates all selected IDs');
  assert.ok(requests.filter(r=>r.url.includes('/tenants/users/items?')).every(r=>Number(new URL(r.url,'http://fixture').searchParams.get('size'))<=100));
  await clickReady('.ant-drawer-open .ant-drawer-close');
  await poll(() => evaluate(`!document.querySelector('.sp-assignment-panel')`), 'tenant assignment drawer closed');
  console.log('PASS: tenant user assignment bounded pages, off-page filters/views, owner protection, failure/retry, duplicate lock and parent isolation');
}
