import assert from 'node:assert/strict';
export async function smokeDnaWorkbench({clickMenu, clickReady, clickText, fill, poll, evaluate, send, reload, fixture}) {
  fixture.enable();
  await clickMenu('元数据标准测试');
  const root = '.nb-tab-panel-active', dialog = '.dna-metadata-dialog .ant-modal';
  const button = async (key, fallback) => {
    const label = await evaluate('window.spI18n.t(' + JSON.stringify(key) + ',' + JSON.stringify(fallback) + ')');
    await clickText(root + ' button', label);
  };
  const readyTree = () => poll(() => evaluate("document.querySelector('" + root + " .ant-tree')?.textContent.includes('public')"), 'metadata tree from the actual selected source');
  await readyTree();
  assert.equal(await evaluate("!!document.querySelector('" + root + " .ant-card')"), false, 'host frame without invented Card wrapper');
  assert.ok(fixture.requests.filter(request => request.path.endsWith('data-sources')).every(request => Number(request.query.get('size')) <= 20));
  await evaluate("document.querySelector('" + root + " .dna-metadata-source .ant-select').dispatchEvent(new MouseEvent('mousedown',{bubbles:true}))");
  await fill(root + ' .dna-metadata-source .ant-select input', 'Source520');
  await poll(() => evaluate("!!document.querySelector('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option[title*=\"Source520\"]')"), 'source beyond first 500');
  await clickReady('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option[title*="Source520"]');
  await poll(() => fixture.requests.some(request => request.path.endsWith('source-id-520/children')), 'source code resolves to its real identifier');
  await readyTree();
  await evaluate("document.querySelector('" + root + " .ant-tree-node-content-wrapper').click()");
  await button('dna.metadata.page.button.createView', '创建视图');
  await poll(() => evaluate("!!document.querySelector('" + dialog + " input#root_name')"), 'platform view form');
  // The SQL field has its own lazy editor boundary; an unrelated input cannot prove it mounted.
  await poll(() => evaluate("!!document.querySelector('" + dialog + " .cm-content')"), 'actual view SQL editor mounted');
  assert.equal(await evaluate("document.querySelector('" + dialog + " .cm-content')?.textContent"), '', 'no executable fake view SQL');
  await clickReady(dialog + ' .ant-modal-close');
  await poll(() => evaluate("!document.querySelector('" + dialog + "')"), 'view cancelled without writes');
  await button('dna.metadata.page.button.createTable', '创建数据表');
  await poll(() => evaluate("!!document.querySelector('" + dialog + " input#root_name')"), 'ordinary typed table form');
  await fill(dialog + ' input#root_name', 'real_table');
  await clickText(dialog + ' .ant-radio-wrapper', '高级 JSON');
  await poll(() => evaluate("!!document.querySelector('" + dialog + " .cm-content')"), 'shared advanced JSON editor');
  const setJson = async value => evaluate("(() => {const view=document.querySelector('" + dialog + " .cm-content').cmTile.root.view;view.dispatch({changes:{from:0,to:view.state.doc.length,insert:" + JSON.stringify(value) + "}});})()");
  const draft = {name: 'real_table', columns: [{name: 'a,b', typeName: 'TEXT', nullable: true}], constraints: []};
  await setJson(JSON.stringify(draft));
  await clickText(dialog + ' .ant-radio-wrapper', '普通');
  await poll(() => evaluate("document.querySelector('" + dialog + " input#root_columns_0_name')?.value==='a,b'"), 'lossless ordinary array field');
  await clickText(dialog + ' .ant-radio-wrapper', '高级 JSON');
  assert.deepEqual(await evaluate("JSON.parse(document.querySelector('" + dialog + " .cm-content').textContent)"), draft);
  await setJson('{"name":');
  await clickText(dialog + ' .ant-radio-wrapper', '普通');
  await poll(() => evaluate("!!document.querySelector('" + dialog + " .ant-alert-error')"), 'invalid JSON cannot silently discard a draft');
  assert.equal(await evaluate("!!document.querySelector('" + dialog + " .cm-content')"), true);
  await setJson(JSON.stringify(draft));
  await clickReady(dialog + ' .ant-modal-close');
  assert.equal(fixture.writes.length, 0);
  const expand = async index => {
    await poll(() => evaluate("!!document.querySelectorAll('" + root + " .ant-tree-switcher')[ " + index + "]"), 'metadata expander');
    await evaluate("document.querySelectorAll('" + root + " .ant-tree-switcher')[" + index + "].click()");
  };
  await expand(0);
  await poll(() => evaluate("document.querySelector('" + root + " .ant-tree')?.textContent.includes('demo.table')"), 'actual table loaded lazily');
  await evaluate("[...document.querySelectorAll('" + root + " .ant-tree-node-content-wrapper')].find(node=>node.textContent.includes('demo.table')).click()");
  await poll(() => evaluate("document.querySelector('" + root + " .ant-table-tbody')?.textContent.includes('a,b')"), 'column structure read model');
  await button('dna.metadata.page.button.addColumn', '添加字段');
  await poll(() => evaluate("!!document.querySelector('" + dialog + " input#root_typeName')"), 'column SForm');
  await fill(dialog + ' input#root_name', 'actual_added');
  await fill(dialog + ' input#root_typeName', 'INTEGER');
  fixture.failWrite();
  await evaluate("(() => {const button=document.querySelector('" + dialog + " .ant-modal-footer .ant-btn-primary');button.click();button.click();})()");
  await poll(() => fixture.writes.length === 1, 'DDL same-frame single flight');
  assert.equal(await evaluate("!!document.querySelector('" + dialog + " .ant-modal-close')"), false, 'pending DDL cannot close its dialog');
  await poll(() => evaluate("document.querySelector('" + dialog + " .ant-alert-error')?.textContent.includes('元数据保存失败')"), 'failure retains the physical-database draft');
  assert.equal(await evaluate("document.querySelector('" + dialog + " input#root_name').value"), 'actual_added');
  await clickReady(dialog + ' .ant-modal-footer .ant-btn-primary');
  await poll(() => fixture.writes.length === 2 && evaluate("!document.querySelector('" + dialog + "')"), 'explicit retry succeeds');
  assert.equal(fixture.writes[1].id, 'source-id-520');
  assert.deepEqual(fixture.writes[1].payload.tablePath, [{type: 'SCHEMA', name: 'public'}, {type: 'TABLE', name: 'demo.table'}]);
  await readyTree();
  await expand(0);
  await poll(() => evaluate("document.querySelector('" + root + " .ant-tree')?.textContent.includes('demo.table')"), 'tree refreshed after DDL');
  await evaluate("[...document.querySelectorAll('" + root + " .ant-tree-node-content-wrapper')].find(node=>node.textContent.includes('demo.table')).click()");
  await poll(() => evaluate("document.querySelector('" + root + " .ant-table-tbody')?.textContent.includes('actual_added')"), 'committed structure refresh');
  assert.equal(fixture.requests.some(request => request.path.endsWith('/preview')), false, 'structure browsing does not automatically read physical data');
  const previewLabel = await evaluate("window.spI18n.t('dna.metadata.page.tab.preview','数据预览')");
  await clickText(root + ' .ant-tabs-tab', previewLabel);
  await poll(() => evaluate("!!document.querySelector('" + root + " tr[data-row-key=\"0-0\"]')"), 'data preview loads only on demand');
  await clickReady(root + ' .ant-pagination-item-27');
  await poll(() => evaluate("document.querySelector('" + root + " tr[data-row-key=\"26-0\"]')?.textContent.includes('520')"), 'physical preview beyond first 500 uses a real server page');
  const structureLabel = await evaluate("window.spI18n.t('dna.metadata.page.tab.structure','结构')");
  await clickText(root + ' .ant-tabs-tab', structureLabel);
  await button('dna.metadata.page.button.addConstraint', '添加约束');
  await poll(() => evaluate("!!document.querySelector('" + dialog + " input#root_name')"), 'typed constraint form');
  await fill(dialog + ' input#root_name', 'ck_new');
  await evaluate("document.querySelector('" + dialog + " .ant-select').dispatchEvent(new MouseEvent('mousedown',{bubbles:true}))");
  const checkLabel = await evaluate("window.spI18n.t('dna.metadata.page.constraintType.CHECK','CHECK')");
  await clickText('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option', checkLabel);
  await poll(() => evaluate("!!document.querySelector('" + dialog + " .cm-content')"), 'CHECK uses the specialized SQL editor');
  // Native CodeMirror change and save in the same browser task must submit the
  // just-entered expression, not the engine's previous empty validation state.
  await evaluate("(() => {const view=document.querySelector('" + dialog + " .cm-content').cmTile.root.view;view.dispatch({changes:{from:0,to:view.state.doc.length,insert:'id >= 0'}});document.querySelector('" + dialog + " .ant-modal-footer .ant-btn-primary').click();})()");
  try {
    await poll(() => fixture.writes.length === 3 && evaluate("!document.querySelector('" + dialog + "')"), 'CHECK saves without inventing local columns or a foreign key');
  } catch (error) {
    console.error('Constraint validation diagnostics', await evaluate("(() => {const element=document.querySelector('" + dialog + " form');let fiber=element?.[Object.keys(element).find(key=>key.startsWith('__reactFiber'))];while(fiber){const state=fiber.stateNode?.state;if(state?.formData)return {text:element.innerText,data:state.formData,errors:state.errors};fiber=fiber.return;}return document.querySelector('" + dialog + "')?.innerText;})()"));
    throw error;
  }
  assert.deepEqual(fixture.writes[2].payload.constraint, {name: 'ck_new', type: 'CHECK', columns: [], reference: null, checkExpression: 'id >= 0'});
  await readyTree();
  await expand(0);
  await poll(() => evaluate("document.querySelector('" + root + " .ant-tree')?.textContent.includes('demo.table')"), 'CHECK commit refresh');
  await evaluate("[...document.querySelectorAll('" + root + " .ant-tree-node-content-wrapper')].find(node=>node.textContent.includes('demo.table')).click()");
  const beforeDelete = fixture.writes.length;
  await button('dna.metadata.page.button.dropObject', '删除对象');
  await poll(() => evaluate("document.querySelector('" + dialog + " .ant-alert-warning')?.textContent.includes('物理数据库')"), 'destructive operation requires an explicit warning');
  assert.equal(fixture.writes.length, beforeDelete, 'opening delete never issues DDL');
  assert.equal(await evaluate("document.querySelector('" + dialog + " input#root_cascade')?.checked"), false, 'cascade is never implicit');
  await clickReady(dialog + ' .ant-modal-close');
  await clickMenu('SQL 控制台');
  await poll(() => evaluate("document.querySelector('.dna-sql-run')?.disabled===false"), 'execute-only SQL capability');
  assert.equal(await evaluate("[...document.querySelectorAll('.dna-sql-toolbar button')].some(button=>button.textContent.includes('执行计划'))"), false);
  await evaluate("document.querySelector('.dna-sql-source-select').dispatchEvent(new MouseEvent('mousedown',{bubbles:true}))");
  await fill('.dna-sql-source-select input', 'Source520');
  await poll(() => evaluate("!!document.querySelector('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option[title*=\"Source520\"]')"), 'SQL shares the same bounded picker');
  await clickReady('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option[title*="Source520"]');
  await poll(() => evaluate("document.querySelector('.dna-sql-statusbar')?.textContent.includes('source-520')"), 'SQL code selection stays separate from metadata source IDs');
  await evaluate("(() => {const button=document.querySelector('.dna-sql-run');button.click();button.click();})()");
  await poll(() => fixture.executions.length === 1, 'authorized SQL submits once');
  assert.equal(fixture.executions[0].catalogCode, 'source-520');
  await poll(() => evaluate("document.querySelector('.dna-sql-console-result-table')?.textContent.includes('actual')"), 'actual SQL response rendered');
  await clickReady('.nb-tabs-bar .ant-tabs-tab-active .ant-tabs-tab-remove');
  await clickMenu('元数据标准测试');
  fixture.readonly(true);
  await evaluate("location.hash='#/smoke/metadata-workbench'");
  await reload();
  await clickMenu('元数据标准测试');
  await readyTree();
  const forbidden = await evaluate("[...document.querySelectorAll('" + root + " .sp-table-toolbar button')].filter(button=>/创建|添加|修改|删除/.test(button.textContent)).length");
  assert.equal(forbidden, 0, 'view-only policy does not invent DDL controls');
  await expand(0);
  await poll(() => evaluate("document.querySelector('" + root + " .ant-tree')?.textContent.includes('demo.table')"), 'readonly metadata table');
  await evaluate("[...document.querySelectorAll('" + root + " .ant-tree-node-content-wrapper')].find(node=>node.textContent.includes('demo.table')).click()");
  assert.equal(await evaluate("[...document.querySelectorAll('" + root + " .ant-tabs-tab')].some(tab=>tab.textContent.includes('预览'))"), false, 'metadata view does not imply data-preview permission');
  await clickMenu('SQL 控制台');
  await poll(() => evaluate("!!document.querySelector('.dna-sql-editor .cm-content')"), 'readonly SQL editor');
  assert.equal(await evaluate("!!document.querySelector('.dna-sql-run')"), false);
  assert.equal(await evaluate("[...document.querySelectorAll('.dna-sql-toolbar button')].some(button=>/执行脚本|执行计划/.test(button.textContent))"), false);
  await evaluate("document.querySelector('.dna-sql-editor .cm-content').cmTile.root.view.focus()");
  await send('Input.dispatchKeyEvent', {type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, modifiers: 2});
  await send('Input.dispatchKeyEvent', {type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, modifiers: 2});
  assert.equal(fixture.executions.length, 1, 'keyboard shortcut enforces the same capability as the toolbar');
  await clickReady('.nb-tabs-bar .ant-tabs-tab-active .ant-tabs-tab-remove');
  await clickMenu('元数据标准测试');
  await clickReady('.nb-tabs-bar .ant-tabs-tab-active .ant-tabs-tab-remove');
  fixture.disable();
  console.log('PASS: bounded JDBC source picker, typed metadata SForms/lossless JSON, no fake SQL, captured DDL retry/lock, explicit non-cascade delete and view-only SQL shortcuts');
}
