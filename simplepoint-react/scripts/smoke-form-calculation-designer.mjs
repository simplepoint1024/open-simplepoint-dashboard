import assert from 'node:assert/strict';

/** Browser integration only; fixed HTTP outputs test rendering, never claim to evaluate a backend formula. */
export async function smokeFormCalculationDesigner({clickReady, clickText, fill, poll, evaluate, save, draft, fixture, textField}) {
  const root = '.nb-tab-panel-active', area = root + ' .sp-form-data-editor';
  let dialog = '.sp-form-field-calculation-modal:not([style*="display: none"]) .ant-modal';
  const control = name => `${dialog} #data_field_${name}`;
  const select = async (selector, text) => {
    await evaluate(`document.querySelector(${JSON.stringify(selector)}).closest('.ant-select').dispatchEvent(new MouseEvent('mousedown',{bubbles:true}))`);
    const listId = await evaluate(`document.querySelector(${JSON.stringify(selector)}).getAttribute('aria-controls')`);
    await clickText(`.ant-select-dropdown:not(.ant-select-dropdown-hidden):has([id="${listId}"]) .ant-select-item-option`, text);
  };
  const edit = async () => {
    await clickText(root + ' .sp-form-designer-tabs .ant-tabs-tab', '数据设计');
    await clickText(area + ' .ant-tabs-tab', '字段');
    await clickText(`${area} [data-row-key="${textField.fieldId}"] button`, '编辑字段');
    await poll(() => evaluate(`!!document.querySelector('${control('calculationMode')}')`), 'calculation mode control');
  };
  await clickText(root + ' .sp-form-designer-tabs .ant-tabs-tab', '表单设计');
  const findField = node => node.fieldId === textField.fieldId ? node : node.children.map(findField).find(Boolean);
  const component = findField(draft().document.scenes.find(scene => scene.type === 'MAIN').root);
  await clickReady(`${root} [data-design-node="${component.componentId}"] > .sp-form-canvas-title`);
  const source = root + ' #design_property_calculationMode';
  await select(source, '公式计算');
  await poll(() => evaluate(`!!document.querySelector('${dialog} .sp-calculator')`), 'canvas property opens the wide formula editor directly');
  await clickText(dialog + ' .ant-modal-footer button', '取消');
  await clickText('.ant-modal-confirm-btns button, .ant-modal-footer button', '放弃修改');
  await poll(() => evaluate(`!document.querySelector('${dialog}')`), 'cancel discards the mode change');
  assert.equal(draft().document.fields.find(field => field.fieldId === textField.fieldId).calculation, undefined);
  assert.equal(await evaluate(`document.querySelector('${source}').closest('.ant-select').textContent.includes('用户填写')`), true);
  await select(source, '公式计算');
  await poll(() => evaluate(`!!document.querySelector('${dialog} .sp-calculator[data-mode="visual"]')`), 'calculator defaults to visual mode');
  await clickText(dialog + ' .sp-calculator [role="tab"]', 'ƒ 表达式');
  await fill(dialog + ' textarea.sp-calculator-expression', '=MISSING_FUNCTION(1)');
  await clickText(dialog + ' .ant-modal-footer button', '应用修改');
  await poll(() => evaluate(`!!document.querySelector('${dialog} .ant-alert-error')`), 'invalid function cannot be applied');
  await clickText(dialog + ' .sp-calculator-error button', '定位错误');
  await poll(() => evaluate(`!!document.querySelector('${dialog} .sp-calculator-block.has-error.is-selected')`), 'invalid function locates its visual node');
  await clickText(dialog + ' .sp-calculator [role="tab"]', 'ƒ 表达式');
  await fill(dialog + ' textarea.sp-calculator-expression', '="公式😀"');
  await clickText(dialog + ' .sp-calculator [role="tab"]', '▦ 可视化');
  await poll(() => evaluate(`document.querySelector('${dialog} .sp-calculator-block[data-kind="STRING"]')?.textContent.includes('公式😀')`), 'text expression reverses to visual blocks');
  await clickText(dialog + ' .ant-modal-footer button', '应用修改');
  await poll(() => evaluate(`!document.querySelector('${dialog}')`), 'calculation applied');
  await save();
  const stored = draft().document.fields.find(field => field.fieldId === textField.fieldId);
  assert.equal(stored.storageMode, 'COMPUTED');
  assert.equal(stored.storageCode, textField.storageCode);
  assert.equal(stored.calculation.expression, '="公式😀"');
  assert.equal(stored.defaultValue, null);
  await clickText(root + ' .sp-form-property-tabs .ant-tabs-tab', '计算公式');
  await poll(() => evaluate(`document.querySelector('${root} .sp-form-calculation-properties')?.textContent.includes('公式校验通过')`), 'property tab shows the validated formula');
  await clickText(root + ' .sp-form-calculation-properties button', '编辑公式');
  await poll(() => evaluate(`!!document.querySelector('${dialog} .sp-calculator[data-mode="visual"]')`), 'existing formula can be edited from properties');
  assert.equal(await evaluate(`document.querySelector('${dialog} .ant-modal-title').textContent.includes(${JSON.stringify(textField.label)})`), true);
  fixture.calculationPreview({values: {[textField.fieldId]: '公式😀'}, details: {}});
  const trialBefore = fixture.calculationReads.length, writesBefore = fixture.writes.length;
  await clickText(dialog + ' .sp-form-calculation-trial .ant-collapse-header', '公式试算');
  await clickText(dialog + ' .sp-form-calculation-trial button', '开始试算');
  await poll(() => fixture.calculationReads.length > trialBefore, 'explicit trial reaches host transport');
  await poll(() => evaluate(`document.querySelector('${dialog} .sp-form-calculation-trial .ant-table-tbody')?.textContent.includes('公式😀')`), 'trial shows typed result');
  assert.equal(fixture.calculationReads.at(-1).document.fields.find(item => item.fieldId === textField.fieldId).calculation.expression, '="公式😀"');
  assert.equal(Object.hasOwn(fixture.calculationReads.at(-1).values, textField.fieldId), false);
  assert.equal(fixture.writes.length, writesBefore, 'trial makes no draft/business write');
  fixture.calculationPreview({values: {[textField.fieldId]: '过期结果'}, details: {}});
  const releaseTrial = fixture.holdNextCalculation(), delayedBefore = fixture.calculationReads.length;
  await clickText(dialog + ' .sp-form-calculation-trial button', '开始试算');
  await poll(() => fixture.calculationReads.length > delayedBefore, 'trial response is held');
  await clickText(dialog + ' .sp-calculator [role="tab"]', 'ƒ 表达式');
  await fill(dialog + ' textarea.sp-calculator-expression', '="新公式"');
  releaseTrial();
  await poll(() => evaluate(`!document.querySelector('${dialog} .sp-form-calculation-trial .ant-table-tbody')`), 'changing the expression clears the old outcome');
  await fill(dialog + ' textarea.sp-calculator-expression', '="公式😀"');
  assert.equal(await evaluate(`document.querySelector('${dialog} .sp-form-calculation-trial').textContent.includes('过期结果')`), false);
  await clickText(dialog + ' .ant-modal-footer button', '取消');
  await poll(() => evaluate(`!document.querySelector('${dialog}')`), 'unchanged formula closes without discard confirmation');
  fixture.calculationPreview({values: {[textField.fieldId]: '公式😀'}, details: {}});
  const before = fixture.calculationReads.length;
  await clickReady(root + ' .sp-form-designer-toolbar button[aria-label="预览"]');
  const preview = '.sp-form-designer-preview:not([style*="display: none"]) .ant-modal';
  await poll(() => evaluate(`document.querySelector('${preview} #form_main_${textField.fieldId}')?.textContent==='公式😀'`), 'trusted preview output displayed');
  assert.equal(await evaluate(`document.querySelector('${preview} #form_main_${textField.fieldId}').matches('.sp-form-display-value')`), true);
  assert.ok(fixture.calculationReads.length > before);
  assert.equal(Object.hasOwn(fixture.calculationReads.at(-1).values, textField.fieldId), false);
  await clickReady(preview + ' .ant-modal-close');
  dialog = '.sp-form-data-modal:not([style*="display: none"]) .ant-modal';
  await edit(); await select(control('calculationMode'), '用户填写');
  await clickText(dialog + ' .ant-modal-footer button', '应用修改');
  await poll(() => evaluate(`!document.querySelector('${dialog}')`), 'stored mode restored'); await save();
  assert.equal(draft().document.fields.find(field => field.fieldId === textField.fieldId).calculation, undefined);
  await clickText(root + ' .sp-form-designer-tabs .ant-tabs-tab', '表单设计');
  assert.equal(await evaluate(`[...document.querySelectorAll('${root} .sp-form-property-tabs .ant-tabs-tab')].some(tab=>tab.textContent.includes('计算公式'))`), false);
  await clickReady(root + ' .sp-form-canvas-node.is-root > .sp-form-canvas-title');
  assert.equal(await evaluate(`!!document.querySelector('${source}')`), false, 'layout components have no calculation source');
  await clickReady(root + ' .sp-form-designer-toolbar button[aria-label="结构导航"]');
  await fill('.sp-form-designer-navigation #designer_navigation_search', textField.label);
  await poll(() => evaluate(`document.querySelector('.sp-form-designer-navigation .ant-tree')?.textContent.includes(${JSON.stringify(textField.label)})`), 'outline search locates the bound field');
  await clickText('.sp-form-designer-navigation .ant-tree-title', textField.label);
  await poll(() => evaluate(`document.querySelector('${root} [data-design-node="${component.componentId}"]')?.classList.contains('is-selected')`), 'outline selection follows canvas and properties');
  await clickReady(root + ' .sp-form-designer-toolbar button[aria-label="配置检查"]');
  await poll(() => evaluate(`document.querySelector('.sp-form-designer-navigation .sp-form-diagnostics')?.textContent.includes('本地配置检查通过')`), 'configuration diagnostics are available');
  await clickReady('.sp-form-designer-navigation .ant-drawer-close');
  console.log('PASS: canvas field source, atomic cancellation, formula summary/edit, invalid function rejection, visual/text roundtrip, shared data entry, read-only trusted preview and stable storage identity');
}
