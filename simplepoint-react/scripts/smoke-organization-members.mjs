import assert from 'node:assert/strict';
export async function smokeOrganizationMembers({clickMenu, clickReady, clickText, fill, poll, evaluate, send, reload, fixture}) {
  const root = '.nb-tab-panel-active', panel = root + ' .organization-members-panel';
  await clickMenu('组织树测试');
  if (await evaluate(`!!document.querySelector('${root} .organization-workspace-list button[aria-label="清除全部筛选"]')`))
    await clickReady(`${root} .organization-workspace-list button[aria-label="清除全部筛选"]`);
  await poll(() => evaluate(`!!document.querySelector('${root} tr[data-row-key="root-0"]')`), 'organization membership source');
  if (!await evaluate(`document.querySelector('${panel} h5')?.textContent==='root-000'`)) await clickReady(`${root} tr[data-row-key="root-0"] td:nth-child(2)`);
  await poll(() => evaluate(`!!document.querySelector('${panel} tr[data-row-key="org-user-0"]') && !document.querySelector('${panel} .ant-spin-spinning')`), 'member page fully loaded');
  await clickReady(`${panel} .ant-pagination-item-2`);
  await poll(() => evaluate(`!!document.querySelector('${panel} tr[data-row-key="org-user-21"]') && !document.querySelector('${panel} .ant-spin-spinning')`), 'descendant organization member');
  await clickReady(`${panel} tr[data-row-key="org-user-21"] .sp-table-button`);
  const type = '.organization-member-type .ant-modal';
  await poll(() => evaluate(`!!document.querySelector('${type} form.rjsf #root_userType')`), 'typed member-type SForm');
  await clickReady(`${root} tr[data-row-key="root-1"] td:nth-child(2)`);
  assert.equal(await evaluate(`document.querySelector('${panel} h5')?.textContent`), 'root-000', 'target cannot change during a member edit');
  const chooseType = async (modal, label) => {
    await evaluate(`document.querySelector('${modal} #root_userType').closest('.ant-select').dispatchEvent(new MouseEvent('mousedown',{bubbles:true}))`);
    await clickText('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option', label);
  };
  await chooseType(type, '引用');
  const before = fixture.organizationWrites.length; fixture.failOrganizationWrite();
  await evaluate(`(() => {const button=document.querySelector('${type} .ant-modal-footer .ant-btn-primary');button.click();button.click();})()`);
  await poll(() => fixture.organizationWrites.length === before + 1, 'same-frame type edit single flight');
  assert.equal(await evaluate(`!!document.querySelector('${type} .ant-modal-close')`), false);
  await poll(() => evaluate(`document.querySelector('${type} .ant-alert-error')?.textContent.includes('组织成员事务保存失败')`), 'member error retains form');
  assert.ok(await evaluate(`document.querySelector('${type}').textContent.includes('引用')`));
  await clickReady(`${type} .ant-modal-footer .ant-btn-primary`);
  await poll(() => evaluate(`!document.querySelector('${type}') && document.querySelector('${panel} tr[data-row-key="org-user-21"]')?.textContent.includes('引用')`), 'type retry rereads its member page');
  assert.equal(fixture.organizationWrites.at(-1).body.orgId, 'child-21', 'type change never transfers child member to the selected ancestor');
  assert.equal(fixture.organizationWrites.at(-1).body.revision, 0);
  const candidates = '.organization-member-candidates .ant-modal';
  await clickText(`${panel} button`, '添加租户用户');
  await poll(() => evaluate(`!!document.querySelector('${candidates} form.rjsf')`), 'candidate options use SForm');
  await fill(`${candidates} .ant-input-search input`, 'Member144');
  await evaluate(`document.querySelector('${candidates} .ant-input-search input').focus()`);
  await send('Input.dispatchKeyEvent', {type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13});
  await send('Input.dispatchKeyEvent', {type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13});
  await poll(() => evaluate(`!!document.querySelector('${candidates} tr[data-row-key="member-144"]') && !document.querySelector('${candidates} .ant-spin-spinning')`), 'actual candidate beyond first 100');
  await clickReady(`${candidates} tr[data-row-key="member-144"] input[type="radio"]`);
  await poll(() => evaluate(`document.querySelector('${candidates} form.rjsf')?.textContent.includes('外部')`), 'candidate existing type preserved before editing');
  await chooseType(candidates, '引用'); fixture.failOrganizationWrite();
  const assignBefore = fixture.organizationWrites.length;
  await evaluate(`(() => {const button=document.querySelector('${candidates} .ant-modal-footer .ant-btn-primary');button.click();button.click();})()`);
  await poll(() => fixture.organizationWrites.length === assignBefore + 1, 'same-frame assignment single flight');
  assert.equal(await evaluate(`!!document.querySelector('${candidates} .ant-modal-close')`), false);
  await poll(() => evaluate(`document.querySelector('${candidates} .ant-alert-error')?.textContent.includes('组织成员事务保存失败')`), 'candidate failure retains selection and type');
  await clickReady(`${candidates} .ant-modal-footer .ant-btn-primary`);
  await poll(() => evaluate(`!document.querySelector('${candidates}')`), 'assignment retry succeeds');
  assert.deepEqual(fixture.organizationWrites.at(-1), {id: 'member-144', body: {orgId: 'root-0', revision: 0, userType: 'REFERENCE'}});
  fixture.readOnlyType(true);
  await reload(); await clickMenu('组织树测试');
  await poll(() => evaluate(`!!document.querySelector('${root} tr[data-row-key="root-0"]')`), 'real readonly schema reload');
  await clickReady(`${root} tr[data-row-key="root-0"] td:nth-child(2)`);
  await poll(() => evaluate(`!!document.querySelector('${panel} tr[data-row-key="org-user-0"]')`), 'readonly field member page');
  assert.equal(await evaluate(`!!document.querySelector('${panel} tr[data-row-key="org-user-0"] .sp-table-button')`), false);
  await clickText(`${panel} button`, '添加租户用户');
  await poll(() => evaluate(`!!document.querySelector('${candidates} tr[data-row-key="member-0"]')`), 'readonly candidate directory');
  assert.equal(await evaluate(`!!document.querySelector('${candidates} #root_userType')`), false);
  await clickReady(`${candidates} tr[data-row-key="member-0"] input[type="radio"]`);
  await clickReady(`${candidates} .ant-modal-footer .ant-btn-primary`);
  await poll(() => evaluate(`!document.querySelector('${candidates}')`), 'readonly type is omitted on assignment');
  assert.equal('userType' in fixture.organizationWrites.at(-1).body, false);
  fixture.readOnlyType(false);
  console.log('PASS: organization member SForms, captured child organization/revision, real off-page candidates, type preservation, failure/retry/single flight, parent selection protection and readonly-field payloads');
}
